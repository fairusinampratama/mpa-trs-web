// Reproducible public-safe inventory; derived output is evidence, never an authoring store.
import fs from "node:fs";
import path from "node:path";
import { canonicalRegistry as r } from "../src/domain/index.ts";
import {
  qualityReport,
  validateRegistry,
  relatedWorks,
  resolvePublicMedia,
} from "../src/domain/validate.ts";
validateRegistry(r);
const out = path.resolve(process.argv[2] || "domain-report");
fs.mkdirSync(out, { recursive: true });
const rows = [
  ...r.activities.map((x) => ({ ...x, domain: "activity" })),
  ...r.works.map((x) => ({ ...x, domain: "work" })),
  ...r.history.map((x) => ({ ...x, domain: "history" })),
].map((x) => ({
  id: x.id,
  domain: x.domain,
  title: x.title,
  classification: x.kind,
  date: x.dates.presentation,
  assertions: x.dates.assertions,
  reconciliation: x.dates.reconciliation,
  place: "places" in x ? x.places : undefined,
  programmeId: "programId" in x ? x.programId : undefined,
  editionId: "editionId" in x ? x.editionId : undefined,
  divisions: "divisionIds" in x ? x.divisionIds : undefined,
  cohorts: "cohortIds" in x ? x.cohortIds : undefined,
  sourceUses: x.sourceUses,
  verification: x.editorial.verification,
  editorialReadiness: x.editorial.readiness,
  publicationScope: x.publication,
  uncertainties: x.uncertainties ?? [],
  originalAvailability: "availability" in x ? x.availability : undefined,
  mediaUses: r.mediaUses.filter((u) => u.recordId === x.id),
}));
const report = {
  contractVersion: r.version,
  counts: {
    activities: r.activities.length,
    genuineActivities: r.activities.filter(
      (a) => a.editorial.verification !== "synthetic",
    ).length,
    expeditions: r.activities.filter((a) => a.kind === "expedition").length,
    pd: r.activities.filter((a) => a.programId === "pd").length,
    works: r.works.length,
    genuineWorkRecords: r.works.filter(
      (w) => w.editorial.verification !== "synthetic",
    ).length,
    history: r.history.length,
    syntheticMembers: r.demoMembers.length,
    relations: r.relations.length,
    sources: r.sources.length,
    publicMedia: r.activities.flatMap((a) => resolvePublicMedia(r, a.id))
      .length,
  },
  quality: qualityReport(r),
  records: rows,
  relationships: r.relations,
  examples: {
    te11Works: relatedWorks(r, "te11").map((w) => w.id),
    te11PeriodAssertions: r.activities.find((a) => a.id === "te11")
      .periodAssertions,
  },
};
fs.writeFileSync(
  out + "/dataset-report.json",
  JSON.stringify(report, null, 2) + "\n",
);
const esc = (s) =>
  String(s ?? "—")
    .replaceAll("|", " / ")
    .replaceAll("\n", " ");
fs.writeFileSync(
  out + "/record-ledger.md",
  "# Populated record and editorial-quality ledger\n\nGenerated by `tools/report_institutional.mjs`; edit canonical records, never this evidence copy. Detailed assertions, publication scope, uncertainty and relationships are in [dataset-report.json](dataset-report.json). All originals and detailed private locators remain outside Git.\n\n| Canonical ID | Domain / classification | Title | Public date label | Source use | Verification / availability |\n| --- | --- | --- | --- | --- | --- |\n" +
    rows
      .map(
        (x) =>
          `| ${x.id} | ${x.domain} / ${x.classification} | ${esc(x.title)} | ${esc(x.date.label)} | ${esc(x.sourceUses.map((u) => u.sourceId + ": " + u.locator).join("; "))} | ${x.verification}${x.originalAvailability ? " / " + x.originalAvailability.state : ""} |`,
      )
      .join("\n") +
    "\n",
);
console.log(JSON.stringify(report.counts));
